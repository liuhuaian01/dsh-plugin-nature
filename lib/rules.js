// 设计原则：
// 1. 规则分「硬伤」和「密度提示」两类。硬伤命中即扣分；密度提示只在单位字数内
//    出现次数超标时才计入，避免把正常中文误判成机器腔。
// 2. 每条规则都带 why（为什么这是 AI 味）和 fix（怎么改），因为诊断报告要能教会
//    人判断，而不只是报一个数字。
// 3. 规则集中在数据层，扫描逻辑在 scan.js，两边解耦。

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** 一组同义词编译成一条正则规则 */
// 长词优先。不排序的话，词表里靠前的短词会先吃掉长词的前半截：
// 「极大地提升」会被匹配成「极大地」，报告只能说「你用了极大地」，
// 说不出完整的搭配，改起来也就没方向。排序后匹配到的是最具体的那个说法。
const anyOf = (words, flags = 'g') =>
  new RegExp([...words].sort((a, b) => b.length - a.length).map(esc).join('|'), flags);

