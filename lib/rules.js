/** 修辞类规则的密度门槛：每千字出现次数超过它才算可疑 */
const RHETORIC_DENSITY = 0.8;

function withSignal(rule) {
  const signal = SIGNAL_BY_ID[rule.id] || 'rhetoric';
  const next = { ...rule, signal, mode: rule.mode || 'hit' };
  // 修辞习惯改成密度判定：真人写四千字用一次「不仅…而且」完全正常，
  // 命中即报会把正常写作判成机器腔。
  if (signal === 'rhetoric' && next.mode === 'hit') {
    next.mode = 'density';
    next.threshold = RHETORIC_DENSITY;
  }
  return next;
}

