/**
 * 把词组组编译成规则对象。
 */
function compilePhraseGroup(group) {
  const rule = {
    id: group.id,
    cat: group.cat,
    sev: group.sev,
    mode: group.mode,
    threshold: group.threshold,
    // 词表组全是套话、黑话、翻译腔这一类，属于模板腔
    signal: 'template',
    label: group.label,
    why: group.why,
    fix: group.fix,
    re: anyOf(group.words),
    vocabulary: group.words,
  };
  // 可选字段要原样带过去。这里漏传过一次：jargon 的 genreThresholds 和
  // excludeAfter 都挂在 group 上，而本函数只挑固定几个字段复制，等于这两项
  // 从来没生效——tech 一直按 0.8 的默认门槛算黑话，「落地窗」也一直算黑话。
  if (group.genreThresholds) rule.genreThresholds = group.genreThresholds;
  if (group.exceptGenres) rule.exceptGenres = group.exceptGenres;
  if (group.excludeAfter) rule.excludeAfter = group.excludeAfter;
  return rule;
}

