/** 词表：用户可通过 config.customBannedWords 追加 */
export function buildCustomRules(words) {
  if (!Array.isArray(words) || words.length === 0) return [];
  const clean = words.map((w) => String(w).trim()).filter(Boolean);
  if (clean.length === 0) return [];
  return [
    {
      id: 'custom-banned',
      cat: '自定义',
      sev: 2,
      mode: 'hit',
      label: '自定义回避词',
      why: '这些词是使用者明确要求在本文里避免的。',
      fix: '换成别的说法，或直接删掉。',
      re: anyOf(clean),
      vocabulary: clean,
    },
  ];
}

