/**
 * 把错别字表编译成一条规则。
 *
 * 合成一条而不是每条一个规则，是为了让报告里只占一行——
 * 一篇文章错五个字，不该把 AI 味分析的版面全挤掉。
 * 具体「哪个词该改成什么」放在 samples 里逐条标出。
 */
export function buildTypoRules() {
  if (TYPO_PAIRS.length === 0) return [];
  const corrections = new Map(TYPO_PAIRS);
  // 长词优先，避免短词抢先匹配
  const pattern = [...TYPO_PAIRS]
    .map(([wrong]) => wrong)
    .sort((a, b) => b.length - a.length)
    .map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|');
  return [
    {
      id: 'typo-collocation',
      cat: '用字错误',
      sev: 2,
      mode: 'hit',
      label: '固定搭配写错',
      why: '这些是固定的成语和词组，写错读者一眼能看出来，属于硬伤。模型生成中文是按概率拼字、不查词典，所以在固定搭配上出错的概率比人还高。',
      fix: '按标注逐个改正。这类错误和文风无关，改了就是改了。',
      re: new RegExp(pattern, 'g'),
      corrections,
    },
  ];
}

